create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_categories_slug on public.categories(slug);
create index if not exists idx_categories_deleted_at on public.categories(deleted_at) where deleted_at is null;

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_tags_slug on public.tags(slug);
create index if not exists idx_tags_deleted_at on public.tags(deleted_at) where deleted_at is null;

create table if not exists public.posts_categories (
  post_id bigint references public.posts(id) on delete cascade,
  category_id bigint references public.categories(id) on delete cascade,
  primary key (post_id, category_id)
);

create index if not exists idx_posts_categories_post_id on public.posts_categories(post_id);
create index if not exists idx_posts_categories_category_id on public.posts_categories(category_id);

create table if not exists public.posts_tags (
  post_id bigint references public.posts(id) on delete cascade,
  tag_id bigint references public.tags(id) on delete cascade,
  primary key (post_id, tag_id)
);

create index if not exists idx_posts_tags_post_id on public.posts_tags(post_id);
create index if not exists idx_posts_tags_tag_id on public.posts_tags(tag_id);

alter table public.categories enable row level security;
alter table public.tags enable row level security;
alter table public.posts_categories enable row level security;
alter table public.posts_tags enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'categories'
      and p.policyname = 'Allow anon select categories'
  ) then
    create policy "Allow anon select categories" on public.categories
    for select to anon
    using (deleted_at is null);
  end if;
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'tags'
      and p.policyname = 'Allow anon select tags'
  ) then
    create policy "Allow anon select tags" on public.tags
    for select to anon
    using (deleted_at is null);
  end if;
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'posts_categories'
      and p.policyname = 'Allow anon select posts_categories'
  ) then
    create policy "Allow anon select posts_categories" on public.posts_categories
    for select to anon
    using (true);
  end if;
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'posts_tags'
      and p.policyname = 'Allow anon select posts_tags'
  ) then
    create policy "Allow anon select posts_tags" on public.posts_tags
    for select to anon
    using (true);
  end if;
end
$$;

