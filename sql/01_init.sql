create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  excerpt text,
  content text,
  author_id uuid references public.users(id) on delete set null,
  published boolean not null default false,
  published_at timestamptz,
  views_count bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_posts_slug on public.posts(slug);
create index if not exists idx_posts_published on public.posts(published, published_at desc);
create index if not exists idx_posts_author_id on public.posts(author_id);
create index if not exists idx_posts_deleted_at on public.posts(deleted_at) where deleted_at is null;

alter table public.posts enable row level security;
do $$
begin
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'posts'
      and p.policyname = 'Allow anon read published'
  ) then
    create policy "Allow anon read published" on public.posts
    for select to anon
    using (published = true and deleted_at is null);
  end if;
end
$$;

