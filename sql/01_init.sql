-- ============================================
-- TRIGGERS FOR UPDATED_AT
-- ============================================

create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger roles_set_updated_at before update on public.roles
for each row execute function public.set_updated_at();

create trigger users_set_updated_at before update on public.users
for each row execute function public.set_updated_at();

create trigger bookings_set_updated_at before update on public.bookings
for each row execute function public.set_updated_at();

create trigger posts_set_updated_at before update on public.posts
for each row execute function public.set_updated_at();

create trigger analytics_summaries_set_updated_at before update on public.analytics_summaries
for each row execute function public.set_updated_at();

create trigger media_set_updated_at before update on public.media
for each row execute function public.set_updated_at();

-- keep categories/tags updated_at fresh
create trigger categories_set_updated_at before update on public.categories
for each row execute function public.set_updated_at();

create trigger tags_set_updated_at before update on public.tags
for each row execute function public.set_updated_at();

