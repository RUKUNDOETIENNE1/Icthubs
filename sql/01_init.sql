create extension if not exists "pgcrypto";

-- ============================================
-- USERS & ROLES MANAGEMENT
-- ============================================

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  permissions jsonb default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  full_name text,
  role_id bigint references public.roles(id) on delete set null,
  is_active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_users_email on public.users(email);
create index if not exists idx_users_role_id on public.users(role_id);
create index if not exists idx_users_deleted_at on public.users(deleted_at) where deleted_at is null;

-- ============================================
-- BOOKINGS (Enhanced)
-- ============================================

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null,
  service text not null,
  message text not null,
  status text not null default 'pending',
  assigned_to uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_bookings_status on public.bookings(status);
create index if not exists idx_bookings_assigned_to on public.bookings(assigned_to);
create index if not exists idx_bookings_created_at on public.bookings(created_at desc);
create index if not exists idx_bookings_deleted_at on public.bookings(deleted_at) where deleted_at is null;

alter table public.bookings enable row level security;
do $$
begin
  if not exists (
    select 1 from pg_policies p
    where p.schemaname = 'public'
      and p.tablename = 'bookings'
      and p.policyname = 'Allow public inserts'
  ) then
    create policy "Allow public inserts" on public.bookings
    for insert to anon
    with check (true);
  end if;
end
$$;

